// gitRepo makes dir a repository with one commit per subject, each dated
// at the given time (committer and author).
func gitRepo(t *testing.T, dir string, commits map[string]string) {
	t.Helper()
	run := func(env []string, args ...string) {
		cmd := exec.Command("git", append([]string{"-C", dir}, args...)...)
		cmd.Env = append(gitEnv(), env...)
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	run(nil, "init", "-q", "-b", "main")
	run(nil, "config", "user.email", "t@example.com")
	run(nil, "config", "user.name", "t")
	run(nil, "config", "commit.gpgsign", "false")
	for subject, when := range commits {
		os.WriteFile(filepath.Join(dir, "f"), []byte(subject), 0o644)
		run(nil, "add", "f")
		run([]string{"GIT_AUTHOR_DATE=" + when, "GIT_COMMITTER_DATE=" + when}, "commit", "-q", "-m", subject)
	}
}

func TestChangelogEntryGrammarAndRepoFiles(t *testing.T) {
	f := newFixture(t)
	alpha := filepath.Join(f.home, "proj", "alpha")
	gitRepo(t, alpha, map[string]string{"feat: early": "2026-10-24T19:00:00Z"})
	f.mustRun("snapshot")
	gitRepo(t, alpha, map[string]string{"fix(list): j at the last row no longer wraps": "2026-10-24T20:30:00Z"})
	f.tool("o-alpha", strings.Replace(alphaCatalog("grep"), `"rows":"skill"`, `"rows":"entry"`, 1))
	f.clock = f.clock.Add(3600e9)
	f.mustRun("snapshot")

	out := f.mustRun("changelog")
	if out != "~/hub/CHANGELOG.md: 2 entries, 2 new\n" {
		t.Fatalf("changelog said %q", out)
	}
	data, err := os.ReadFile(filepath.Join(f.home, "hub", "CHANGELOG.md"))
	if err != nil {
		t.Fatal(err)
	}
	text := string(data)
	newest := text[strings.Index(text, "## 2026-10-24 21:10"):strings.Index(text, "## 2026-10-24 20:10")]
	want := "## 2026-10-24 21:10\n\n" +
		"### Nouns and verbs\n" +
		"- added: `o-alpha skill grep`\n" +
		"- changed: `o-alpha skill list` rows `entry`; was `skill`\n\n" +
		"### Commits\n" +
		"- fixed: j at the last row no longer wraps (alpha " + head(t, alpha) + ")\n\n"
	if newest != want {
		t.Fatalf("newest entry:\n%q\nwant:\n%q", newest, want)
	}
	first := text[strings.Index(text, "## 2026-10-24 20:10"):]
	for _, line := range []string{
		"- added: `o-alpha` at `~/bin/o-alpha`, 1 noun, 2 verbs, 1 param, 1 binding, 1 page\n",
		"- added: noun `ochazuke app` with verbs `quit`, 1 binding\n",
		"- added: nabe page `alpha` for `~/bin/o-alpha`, order 0\n",
		"- added: project `alpha` (o-proj) at `~/proj/alpha`, hub link\n",
	} {
		if !strings.Contains(first, line) {
			t.Fatalf("first entry lacks %q:\n%s", line, first)
		}
	}
	grammar := regexp.MustCompile("^(- (added|changed|removed|fixed|shadow): .+|- [a-z0-9-]+: [0-9a-f]+ .+|## .+|### .+|# Changelog|Generated by .+|)$")
	for _, line := range strings.Split(text, "\n") {
		if !grammar.MatchString(line) {
			t.Fatalf("line outside the grammar: %q", line)
		}
		if strings.HasPrefix(line, "- changed: ") && !strings.Contains(line, "; was ") {
			t.Fatalf("changed line without ; was: %q", line)
		}
	}
	// Idempotent: a second run adds nothing and leaves the file alone.
	if out := f.mustRun("changelog"); out != "~/hub/CHANGELOG.md: 2 entries, 0 new\n" {
		t.Fatalf("second changelog said %q", out)
	}
	if again, _ := os.ReadFile(filepath.Join(f.home, "hub", "CHANGELOG.md")); string(again) != text {
		t.Fatal("second run changed the file")
	}

	// --repo filters; --write-repos prepends to the repo's own file.
	os.WriteFile(filepath.Join(alpha, "CHANGELOG.md"), []byte("# alpha changes\n\n## v0.1.0\n\n- added: everything\n"), 0o644)
	if out := f.mustRun("changelog", "--repo", "alpha"); strings.Contains(out, "o-alpha skill grep") || !strings.Contains(out, "- fixed: j at the last row") {
		t.Fatalf("--repo alpha:\n%s", out)
	}
	f.mustRun("changelog", "--write-repos")
	got, _ := os.ReadFile(filepath.Join(alpha, "CHANGELOG.md"))
	if !strings.HasPrefix(string(got), "# alpha changes\n\n## 2026-10-24 21:10\n\n### Commits\n- fixed: ") || !strings.HasSuffix(string(got), "## v0.1.0\n\n- added: everything\n") {
		t.Fatalf("alpha CHANGELOG.md:\n%s", got)
	}
}

func head(t *testing.T, dir string) string {
	t.Helper()
	h, err := git(dir, "rev-parse", "--short=7", "HEAD")
	if err != nil {
		t.Fatal(err)
	}
	return h
}

func TestReposSeededFromHubLinksAndFrameworkRepos(t *testing.T) {
	f := newFixture(t)
	gitRepo(t, filepath.Join(f.home, "proj", "alpha"), map[string]string{"feat: one": "2026-10-24T19:00:00Z"})
	// A link into a directory that is not a repository of its own.
	os.MkdirAll(filepath.Join(f.home, "hub", "ai", "utils"), 0o755)
	os.Symlink(filepath.Join(f.home, "hub", "ai", "utils"), filepath.Join(f.home, "hub", "o", "utils"))
	out := f.mustRun("repos")
	if f.err.String() != "seeded ~/.config/o-inventory/repos.json\n" {
		t.Fatalf("stderr %q", f.err.String())
	}
	var repos []Repo
	if err := json.Unmarshal([]byte(out), &repos); err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, r := range repos {
		got = append(got, r.Name+"="+r.Path)
	}
	want := "alpha=~/proj/alpha matomeru=~/proj/matomeru ochazuke=~/proj/ochazuke oden=~/proj/oden"
	if strings.Join(got, " ") != want {
		t.Fatalf("repos %v, want %s", got, want)
	}
	// The config is read, not reseeded.
	os.WriteFile(filepath.Join(f.home, ".config", "o-inventory", "repos.json"), []byte(`[{"name":"x","path":"~/x"}]`), 0o644)
	if out := f.mustRun("repos"); !strings.Contains(out, `"x"`) || f.err.String() != "" {
		t.Fatalf("second repos %q %q", out, f.err.String())
	}
}
